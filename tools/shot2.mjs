import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await p.waitForFunction(() => document.querySelector('#loading')?.hasAttribute('hidden') === true, { timeout: 90000 });
await p.waitForTimeout(1200);
await p.evaluate(() => window.__aranya.setTime(18.33, true));
await p.evaluate(() => window.__aranya.director.goTo(2));
await p.waitForTimeout(2200);
await p.evaluate(() => window.__aranya.director.skip());
await p.waitForTimeout(900);
await p.screenshot({ path: 'shots/06-hall.png' });
await p.evaluate(() => window.__aranya.director.goTo(3));
await p.waitForTimeout(2200);
await p.evaluate(() => window.__aranya.director.skip());
await p.waitForTimeout(900);
await p.screenshot({ path: 'shots/07-terrace.png' });
console.log('errors', JSON.stringify(errs));
await b.close();
