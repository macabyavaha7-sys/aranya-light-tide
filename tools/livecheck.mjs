import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on('pageerror', e => errors.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
p.on('requestfailed', r => errors.push('failed: ' + r.url() + ' ' + r.failure()?.errorText));
const t0 = Date.now();
await p.goto('https://macabyavaha7-sys.github.io/aranya-light-tide/', { waitUntil: 'networkidle', timeout: 90000 });
await p.waitForFunction(() => document.querySelector('#loading')?.hasAttribute('hidden') === true, { timeout: 90000 });
await p.waitForTimeout(2500);
console.log('loaded in', ((Date.now()-t0)/1000).toFixed(1), 's');
console.log('model', await p.evaluate(() => !!window.__aranya?.world?.scene.getObjectByName('Chapel')));
console.log('clock', await p.textContent('#clock'));
await p.screenshot({ path: 'shots/live-desktop.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await m.goto('https://macabyavaha7-sys.github.io/aranya-light-tide/', { waitUntil: 'networkidle', timeout: 90000 });
await m.waitForFunction(() => document.querySelector('#loading')?.hasAttribute('hidden') === true, { timeout: 90000 });
await m.waitForTimeout(2000);
await m.screenshot({ path: 'shots/live-mobile.png' });
console.log('errors', JSON.stringify(errors.slice(0,6)));
await b.close();
